"""Schemas for the RAG-grounded AI Trip Planner and conversational refinement."""

from decimal import Decimal

from pydantic import BaseModel, ConfigDict, Field

from app.core.enums import BudgetLevel, ChatRole, FoodType, PlaceCategory


class TripPlanRequest(BaseModel):
    """User preferences submitted to generate a personalized itinerary."""

    state_id: int = Field(ge=1, description="Target state ID")
    duration_days: int = Field(default=3, ge=1, le=14, description="Number of trip days (1-14)")
    total_budget: Decimal = Field(default=Decimal("15000"), gt=0, description="Total budget in INR")
    budget_tier: BudgetLevel = Field(
        default=BudgetLevel.MEDIUM, description="Travel comfort tier (low, medium, high)"
    )
    food_preference: FoodType | None = Field(
        default=None, description="Culinary preference (veg, non_veg, vegan)"
    )
    travel_month: str | None = Field(default=None, description="Month of travel (e.g. November)")
    interests: list[PlaceCategory] = Field(
        default_factory=list, description="Preferred attraction categories"
    )


class ItineraryPlaceItem(BaseModel):
    """A verified attraction scheduled in a day itinerary."""

    model_config = ConfigDict(frozen=True)

    place_id: int
    place_name: str
    category: PlaceCategory
    description: str
    entry_fee: Decimal = Decimal("0")
    recommended_time: str = "Morning"
    is_hidden_gem: bool = False


class ItineraryMealItem(BaseModel):
    """A regional dish recommendation for a day."""

    model_config = ConfigDict(frozen=True)

    meal_type: str = "Lunch"
    dish_name: str
    food_type: FoodType
    avg_price: Decimal = Decimal("150")


class DayPlan(BaseModel):
    """One day schedule inside the itinerary."""

    model_config = ConfigDict(frozen=True)

    day_number: int
    theme: str
    destination_name: str
    places: list[ItineraryPlaceItem] = Field(default_factory=list)
    meals: list[ItineraryMealItem] = Field(default_factory=list)
    day_budget: Decimal
    travel_tips: str


class BudgetBreakdown(BaseModel):
    """Itemized budget summary across the full trip."""

    model_config = ConfigDict(frozen=True)

    accommodation_estimate: Decimal
    food_estimate: Decimal
    activities_and_entry: Decimal
    local_transport_estimate: Decimal
    total_estimated_cost: Decimal


class TripPlanResponse(BaseModel):
    """Complete structured itinerary generated by the RAG planner."""

    model_config = ConfigDict(frozen=True)

    state_id: int
    state_name: str
    trip_title: str
    total_days: int
    total_budget: Decimal
    budget_breakdown: BudgetBreakdown
    days: list[DayPlan]
    overall_advice: str


class ChatTurn(BaseModel):
    """A single turn in the conversational refinement history."""

    role: ChatRole
    content: str


class PlannerChatRequest(BaseModel):
    """Payload to refine or ask questions about a generated itinerary."""

    state_id: int
    message: str = Field(min_length=1, max_length=1000, description="User instruction or question")
    current_plan: TripPlanResponse
    chat_history: list[ChatTurn] = Field(default_factory=list)
    plan_id: int | None = Field(default=None, description="Saved plan ID if already saved")


class PlannerChatResponse(BaseModel):
    """Bot response to user follow-up message."""

    model_config = ConfigDict(frozen=True)

    reply: str
    updated_plan: TripPlanResponse | None = None
